import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { safeUrl, mergeSources, runnable, contactAge, type Company } from '../src/focus/model';
import { launchLeadFinderSchema } from '../../backend/src/lead-finder-launch';
assert.equal(safeUrl('javascript:alert(1)'), '');
assert.equal(safeUrl('data:text/html,test'), '');
assert.equal(safeUrl('https://user:password@example.com'), '');
assert.equal(safeUrl('example.com'), 'https://example.com/');
const base = { id: 'internal', code: 'serper', name: 'Serper', category: 'web', accessMode: 'api' };
assert.equal(runnable(mergeSources([base], [{ ...base, id: 'serper', ready: true, enabled: true }])[0]), true);
assert.equal(runnable({ ...base, ready: true }), false);
assert.equal(runnable({ ...base, accessMode: 'manual_assisted', ready: true, enabled: true }), false);
const company = { createdAt: new Date().toISOString(), extractedContacts: [] } as unknown as Company;
assert.equal(contactAge(company).known, false);
assert.equal(contactAge({ ...company, extractedContacts: [{ observedAt: '2020-01-01' }] } as Company).stale, true);
const payload = JSON.parse(readFileSync('../work/focus-launch-test-payload.json', 'utf8'));
const parsed = launchLeadFinderSchema.parse(payload);
assert.deepEqual(parsed.campaign.snapshot?.markets, ['Germany']);
assert.equal(parsed.strategy.providerPlan?.length, 1);
assert.equal(parsed.strategy.providerPlan?.[0].pageLimit, 1);
console.log('Focus model checks and launch API contract: passed');
